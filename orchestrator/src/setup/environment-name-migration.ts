const LEGACY_ENVIRONMENT_NAMES = new Map<string, string>(LEGACY_ENVIRONMENT_NAME_PAIRS)

const DYNAMIC_ENVIRONMENT_NAME_FAMILIES = [
  ['ORCH_PORTS_', 'BOTTEGA_PORTS_'],
  ['ORCH_DB_', 'BOTTEGA_ORCHESTRATOR_DB_'],
  ['ORCH_ALLOC_', 'BOTTEGA_ALLOC_'],
] as const

export type LegacyEnvironmentNamePair = (typeof LEGACY_ENVIRONMENT_NAME_PAIRS)[number]

/** The sealed subset is deliberately selected from the authority table, never restated. */
export const LEGACY_ENVIRONMENT_SECRET_NAMES = LEGACY_ENVIRONMENT_NAME_PAIRS.filter(
  (
    pair,
  ): pair is Extract<
    LegacyEnvironmentNamePair,
    readonly ['ORCH_RECORD_URL' | 'ORCH_RECORD_MIGRATE_URL', string]
  > => pair[0] === 'ORCH_RECORD_URL' || pair[0] === 'ORCH_RECORD_MIGRATE_URL',
)

export function replacementEnvironmentName(name: string): string | null {
  const fixed = LEGACY_ENVIRONMENT_NAMES.get(name)
  if (fixed) return fixed
  for (const [oldPrefix, newPrefix] of DYNAMIC_ENVIRONMENT_NAME_FAMILIES) {
    if (name.startsWith(oldPrefix) && name.length > oldPrefix.length) {
      return `${newPrefix}${name.slice(oldPrefix.length)}`
    }
  }
  return null
}

export type LegacyEnvironmentNameMatch = {
  name: string
  replacement: string
  index: number
}

/** Finds every whole legacy environment token, including dynamic-family members. */
export function legacyEnvironmentNameMatches(text: string): LegacyEnvironmentNameMatch[] {
  const matches: LegacyEnvironmentNameMatch[] = []
  const token = /[A-Z][A-Z0-9_]*/g
  for (const found of text.matchAll(token)) {
    const name = found[0]
    const replacement = replacementEnvironmentName(name)
    if (replacement) matches.push({ name, replacement, index: found.index })
  }
  return matches
}

if (import.meta.main) {
  const [command, path] = process.argv.slice(2)
  if (command !== 'check-file' || !path) process.exit(2)
  const matches = legacyEnvironmentNameMatches(await Bun.file(path).text())
  if (matches.length) {
    console.error([...new Set(matches.map(({ name }) => name))].join(', '))
    process.exit(1)
  }
}
