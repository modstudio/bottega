/** Hosted-record sync module allowlists, split from the root record manifest to keep each concern under its file ceiling. */
import { dirname, normalize } from 'node:path'

type RecordSyncModule = { file: string; allowed: string[] }

const module = (file: string, allowed: string[]): RecordSyncModule => ({
  file,
  allowed: allowed.map((target) =>
    target.startsWith('.') ? normalize(`${dirname(file)}/${target}`) : target,
  ),
})

