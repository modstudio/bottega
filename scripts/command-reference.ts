import type {
  DocumentationArgument,
  DocumentationCommand,
  DocumentationGroup,
  DocumentationInventory,
  DocumentationOptionDefault,
  DocumentationOptionDetail,
} from './command-descriptions.ts'

export const REGENERATE_COMMAND = 'bun scripts/reference.ts --write'

export type ReferencePage = {
  file: string
  content: string
}

const GENERATED_HEADER = `> Generated by \`${REGENERATE_COMMAND}\`. Do not edit by hand.`

function argumentToken(argument: DocumentationArgument): string {
  const inner = argument.variadic ? `${argument.name}...` : argument.name
  return argument.required ? `<${inner}>` : `[${inner}]`
}

function optionToken(option: DocumentationOptionDetail): string {
  const name = option.flags.split(/[ ,|]+/).find((part) => part.startsWith('--')) ?? option.flags
  const body = option.valuePlaceholder ? `${name} ${option.valuePlaceholder}` : name
  return `[${body}]`
}

function synopsis(command: DocumentationCommand): string {
  const parts = [command.spelling]
  for (const argument of command.arguments) parts.push(argumentToken(argument))
  if (!command.optionsByHelp) {
    for (const option of command.options) parts.push(optionToken(option))
  }
  return parts.join(' ')
}

function defaultText(value: DocumentationOptionDefault): string {
  if (value.kind === 'cwd') return 'the current working directory'
  if (value.kind === 'env') return `the value of ${value.name}`
  return value.text
}

function optionLine(option: DocumentationOptionDetail): string {
  const placeholder = option.valuePlaceholder ? ` ${option.valuePlaceholder}` : ''
  const flag =
    option.flags.includes('<') || option.flags.includes('[')
      ? option.flags
      : `${option.flags}${placeholder}`
  const declared = option.default ? ` (default: ${defaultText(option.default)})` : ''
  return `- \`${flag}\`: ${option.description}${declared}`
}

function commandAnchor(spelling: string): string {
  return spelling.replaceAll(' ', '-')
}

function relatedLines(
  command: DocumentationCommand,
  siblings: readonly DocumentationCommand[],
): string[] {
  const file = `${command.group}.md`
  const links = [`- [${command.group}](./${file})`]
  for (const sibling of siblings) {
    if (sibling.spelling === command.spelling) continue
    links.push(`- [${sibling.spelling}](./${file}#${commandAnchor(sibling.spelling)})`)
  }
  return links
}

function renderCommand(
  command: DocumentationCommand,
  siblings: readonly DocumentationCommand[],
): string {
  const sections = [
    `## ${command.spelling}`,
    '',
    `**Synopsis:** \`${synopsis(command)}\``,
    '',
    command.description,
  ]
  if (command.optionsByHelp) {
    sections.push('', '### Options', '', 'Options are documented by `--help`.')
  } else if (command.options.length > 0) {
    sections.push('', '### Options', '', ...command.options.map(optionLine))
  }
  if (command.examples.length > 0) {
    sections.push('', '### Examples', '', ...command.examples.map((example) => `- \`${example}\``))
  }
  sections.push('', '### Related', '', ...relatedLines(command, siblings), '')
  return sections.join('\n')
}

function groupCommands(
  commands: readonly DocumentationCommand[],
  group: string,
): DocumentationCommand[] {
  return commands
    .filter((command) => command.group === group)
    .sort((left, right) => left.spelling.localeCompare(right.spelling))
}

function renderGroupPage(
  group: DocumentationGroup,
  commands: readonly DocumentationCommand[],
): string {
  const members = groupCommands(commands, group.name)
  const body = members.map((command) => renderCommand(command, members)).join('\n')
  return `${GENERATED_HEADER}\n\n# ${group.name}\n\n${body}`
}

function renderIndex(groups: readonly DocumentationGroup[]): string {
  const lines = groups.map(
    (group) => `- [${group.name}](./${group.name}.md) — ${group.description}`,
  )
  return `${GENERATED_HEADER}\n\n# Command reference\n\n${lines.join('\n')}\n`
}

/** Render one Markdown page per group plus the parent index. Group order follows the inventory groups list (route order). Commands on a group page are sorted by spelling. */
export function renderReferencePages(inventory: DocumentationInventory): ReferencePage[] {
  const pages: ReferencePage[] = [{ file: 'index.md', content: renderIndex(inventory.groups) }]
  for (const group of inventory.groups) {
    pages.push({
      file: `${group.name}.md`,
      content: renderGroupPage(group, inventory.commands),
    })
  }
  return pages
}
