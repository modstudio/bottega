// concern: postgres-schema-run
/** Knows the hosted run record shape. Must not know local execution state or synchronization. */
import { sql } from 'drizzle-orm'
import {
  type AnyPgColumn,
  bigint,
  boolean,
  check,
  doublePrecision,
  index,
  integer,
  jsonb,
  pgPolicy,
  pgTable,
  text,
  timestamp,
  unique,
  uuid,
} from 'drizzle-orm/pg-core'
import {
  machine,
  project,
  RECORD_OWNER_ROLE,
  spaceIdentity,
  tenantPolicies,
  user,
} from './schema.ts'
import { hubTask } from './schema-hub.ts'

export const run = pgTable.withRLS(
  'run',
  {
    id: uuid().primaryKey(),
    evidenceSeq: bigint('evidence_seq', { mode: 'bigint' }).notNull(),
    number: integer(),
    spaceId: spaceIdentity(),
    projectId: uuid('project_id').references(() => project.id),
    machineId: uuid('machine_id')
      .notNull()
      .references(() => machine.id),
    startedByUserId: uuid('started_by_user_id')
      .notNull()
      .references(() => user.id),
    startedAt: timestamp('started_at', { withTimezone: true }).notNull(),
    finishedAt: timestamp('finished_at', { withTimezone: true }),
    agent: text().notNull(),
    job: text().notNull(),
    promptSha: text('prompt_sha').notNull(),
    specSha: text('spec_sha'),
    promptBytes: bigint('prompt_bytes', { mode: 'bigint' }).notNull(),
    promptHead: text('prompt_head').notNull(),
    taskKey: text('task_key'),
    taskId: uuid('task_id').references(() => hubTask.id, { onDelete: 'set null' }),
    label: text(),
    lens: text(),
    latencyMs: bigint('latency_ms', { mode: 'bigint' }),
    exitCode: integer('exit_code'),
    outputBytes: bigint('output_bytes', { mode: 'bigint' }),
    vendorTokens: bigint('vendor_tokens', { mode: 'bigint' }),
    modelCalls: integer('model_calls'),
    peakCallTokens: bigint('peak_call_tokens', { mode: 'bigint' }),
    quotaUsedPercentStart: doublePrecision('quota_used_percent_start'),
    quotaUsedPercentEnd: doublePrecision('quota_used_percent_end'),
    quotaWindowMinutes: integer('quota_window_minutes'),
    quotaResetsAt: bigint('quota_resets_at', { mode: 'bigint' }),
    vendorCostUsd: doublePrecision('vendor_cost_usd'),
    vendorInputTokens: bigint('vendor_input_tokens', { mode: 'bigint' }),
    vendorOutputTokens: bigint('vendor_output_tokens', { mode: 'bigint' }),
    vendorEstimatedCostUsd: doublePrecision('vendor_estimated_cost_usd'),
    vendorCostSource: text('vendor_cost_source'),
    resourceCpuMs: bigint('resource_cpu_ms', { mode: 'bigint' }),
    resourcePeakRssBytes: bigint('resource_peak_rss_bytes', { mode: 'bigint' }),
    resourceSamples: integer('resource_samples'),
    resourceSource: text('resource_source'),
    probe: boolean().notNull(),
    failureKind: text('failure_kind'),
    status: text().notNull(),
    error: text(),
    retryOf: uuid('retry_of').references((): AnyPgColumn => run.id),
    parentRunId: uuid('parent_run_id').references((): AnyPgColumn => run.id),
    turn: integer().notNull(),
    filesChanged: integer('files_changed'),
    changedPaths: jsonb('changed_paths'),
    linesAdded: integer('lines_added'),
    linesRemoved: integer('lines_removed'),
    testsRan: integer('tests_ran'),
    testsPassed: integer('tests_passed'),
    testsClaimDisagrees: boolean('tests_claim_disagrees'),
    deviations: integer(),
    escalations: integer(),
    stack: text(),
    model: text(),
    executor: text(),
    evidenceExcluded: text('evidence_excluded'),
    inputTree: text('input_tree'),
    headCommit: text('head_commit'),
    reviewRef: text('review_ref'),
    reviewRole: text('review_role'),
    branch: text(),
    baseCommit: text('base_commit'),
    mintedBranch: text('minted_branch'),
    docsInjected: integer('docs_injected'),
    docRevisions: jsonb('doc_revisions'),
    canonSha: text('canon_sha'),
    transport: text(),
    sessionId: text('session_id'),
    routeReason: text('route_reason'),
    noFailover: boolean('no_failover').notNull(),
    automaticFailover: boolean('automatic_failover').notNull(),
    outsideWorktreeWrites: jsonb('outside_worktree_writes'),
    reviewProvenance: jsonb('review_provenance'),
    provenanceStatus: text('provenance_status'),
    workPreserved: boolean('work_preserved').notNull(),
    closeOutOutcome: text('close_out_outcome'),
    closeOutDetail: text('close_out_detail'),
    provisioningKind: text('provisioning_kind'),
    provisioningMs: bigint('provisioning_ms', { mode: 'bigint' }),
    provisioningPhases: jsonb('provisioning_phases'),
    provisioningEntries: bigint('provisioning_entries', { mode: 'bigint' }),
    provisioningEntriesLimited: boolean('provisioning_entries_limited'),
    provisioningHostLoad: jsonb('provisioning_host_load'),
    hostAdmissionFirst: jsonb('host_admission_first'),
    hostAdmission: jsonb('host_admission'),
    provisioningOutcome: text('provisioning_outcome'),
    provisioningEntryRoots: jsonb('provisioning_entry_roots'),
    withheldFields: jsonb('withheld_fields'),
    createdAt: timestamp('created_at', { withTimezone: true }).notNull(),
    updatedAt: timestamp('updated_at', { withTimezone: true }).notNull(),
  },
  (table) => [
    index('run_space_evidence_seq_idx').on(table.spaceId, table.evidenceSeq),
    index('run_space_started_id_idx').on(table.spaceId, table.startedAt.desc(), table.id.desc()),
    index('run_task_id_idx').on(table.taskId),
    index('run_unlinked_task_key_idx')
      .on(table.spaceId, table.taskKey)
      .where(sql`${table.taskId} IS NULL AND ${table.taskKey} IS NOT NULL`),
    check(
      'run_review_role_check',
      sql`${table.reviewRole} IS NULL OR ${table.reviewRole} IN ('round', 'supplementary')`,
    ),
    check(
      'run_executor_check',
      sql`${table.executor} IS NULL OR ${table.executor} IN ('external', 'harness')`,
    ),
    ...tenantPolicies('run', table.spaceId),
  ],
)

export const routingEvidenceHead = pgTable.withRLS(
  'routing_evidence_head',
  {
    id: uuid().primaryKey(),
    spaceId: spaceIdentity(),
    sequence: bigint({ mode: 'bigint' }).notNull(),
  },
  // Triggers write evidence heads inside a statement whose row policy already judged the caller.
  (table) => [
    unique('routing_evidence_head_space_unique').on(table.spaceId),
    pgPolicy('routing_evidence_head_space_select', {
      for: 'select',
      using: sql`${table.spaceId} = nullif(current_setting('app.space_id', true), '')::uuid`,
    }),
    pgPolicy('routing_evidence_head_space_insert', {
      for: 'insert',
      withCheck: sql`${table.spaceId} = nullif(current_setting('app.space_id', true), '')::uuid`,
    }),
    pgPolicy('routing_evidence_head_space_update', {
      for: 'update',
      using: sql`${table.spaceId} = nullif(current_setting('app.space_id', true), '')::uuid`,
      withCheck: sql`${table.spaceId} = nullif(current_setting('app.space_id', true), '')::uuid`,
    }),
    pgPolicy('routing_evidence_head_owner_all', {
      for: 'all',
      to: RECORD_OWNER_ROLE,
      using: sql`true`,
      withCheck: sql`true`,
    }),
  ],
)

export const runScore = pgTable.withRLS(
  'run_score',
  {
    runId: uuid('run_id').primaryKey(),
    spaceId: spaceIdentity(),
    delivery: text().notNull(),
    quality: text(),
    fidelity: text(),
    note: text(),
    scoredAt: timestamp('scored_at', { withTimezone: true }).notNull(),
    scoredBy: text('scored_by').notNull(),
    withheldFields: jsonb('withheld_fields'),
    updatedAt: timestamp('updated_at', { withTimezone: true }).notNull(),
  },
  (table) => [
    check('run_score_delivery_check', sql`${table.delivery} IN ('none', 'partial', 'full')`),
    check(
      'run_score_quality_check',
      sql`${table.quality} IS NULL OR ${table.quality} IN ('wrong', 'mixed', 'right')`,
    ),
    check(
      'run_score_fidelity_check',
      sql`${table.fidelity} IS NULL OR ${table.fidelity} IN ('drifted', 'partial', 'faithful')`,
    ),
    check(
      'run_score_delivery_quality_check',
      sql`(${table.delivery} = 'none') = (${table.quality} IS NULL)`,
    ),
    ...tenantPolicies('run_score', table.spaceId),
  ],
)

/** Survives a void issued before the run row exists so a later run upsert cannot drop it. */
export const runExclusion = pgTable.withRLS(
  'run_exclusion',
  {
    runId: uuid('run_id').primaryKey(),
    spaceId: spaceIdentity(),
    reason: text().notNull(),
    excludedAt: timestamp('excluded_at', { withTimezone: true }).notNull(),
    supersededAt: timestamp('superseded_at', { withTimezone: true }),
    supersededBy: text('superseded_by'),
    supersedeNote: text('supersede_note'),
  },
  (table) => [...tenantPolicies('run_exclusion', table.spaceId)],
)
